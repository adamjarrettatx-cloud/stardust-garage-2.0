function formatInline(text) {
  return text.split(/(\*\*[^*]+\*\*)/g).filter(Boolean).map((part, index) => {
    if (part.startsWith('**') && part.endsWith('**')) return <strong key={index}>{part.slice(2, -2)}</strong>;
    return part;
  });
}

function LegalBody({ source }) {
  const blocks = [];
  let paragraph = [];
  let list = [];
  const flushParagraph = () => { if (paragraph.length) { blocks.push(<p key={`p-${blocks.length}`}>{formatInline(paragraph.join(' '))}</p>); paragraph = []; } };
  const flushList = () => { if (list.length) { blocks.push(<ul key={`l-${blocks.length}`}>{list.map((item, index) => <li key={index}>{formatInline(item)}</li>)}</ul>); list = []; } };
  for (const rawLine of source.split('\n')) {
    const line = rawLine.trim();
    if (!line) { flushParagraph(); flushList(); continue; }
    if (line.startsWith('## ')) { flushParagraph(); flushList(); blocks.push(<h2 key={`h2-${blocks.length}`}>{formatInline(line.slice(3))}</h2>); continue; }
    if (line.startsWith('### ')) { flushParagraph(); flushList(); blocks.push(<h3 key={`h3-${blocks.length}`}>{formatInline(line.slice(4))}</h3>); continue; }
    if (line.startsWith('- ')) { flushParagraph(); list.push(line.slice(2)); continue; }
    flushList(); paragraph.push(line);
  }
  flushParagraph(); flushList();
  return <div className="legal-body">{blocks}</div>;
}

